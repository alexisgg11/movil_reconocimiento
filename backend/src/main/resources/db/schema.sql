CREATE SCHEMA IF NOT EXISTS reconocimiento;
CREATE TABLE IF NOT EXISTS reconocimiento.persona (
 dni VARCHAR(8) PRIMARY KEY, nombre VARCHAR(120) NOT NULL,
 activo BOOLEAN NOT NULL DEFAULT TRUE, foto TEXT NOT NULL DEFAULT '', creado TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS reconocimiento.rostro (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 dni VARCHAR(8) NOT NULL REFERENCES reconocimiento.persona(dni), vector TEXT NOT NULL, modelo VARCHAR(80) NOT NULL
);
CREATE INDEX IF NOT EXISTS rostro_persona ON reconocimiento.rostro(dni);
ALTER TABLE reconocimiento.persona ADD COLUMN IF NOT EXISTS origen_rostro VARCHAR(16) NOT NULL DEFAULT 'CAMARA';
CREATE TABLE IF NOT EXISTS reconocimiento.dispositivo (
 id VARCHAR(64) PRIMARY KEY, dni VARCHAR(8) NOT NULL UNIQUE REFERENCES reconocimiento.persona(dni), clave TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS reconocimiento.configuracion (
 id INT PRIMARY KEY CHECK(id=1), nombre VARCHAR(100) NOT NULL DEFAULT 'Sede principal',
 latitud DOUBLE PRECISION, longitud DOUBLE PRECISION, radio DOUBLE PRECISION NOT NULL DEFAULT 100,
 red VARCHAR(50) NOT NULL DEFAULT '', umbral DOUBLE PRECISION NOT NULL DEFAULT 0.80,
 revision BIGINT NOT NULL DEFAULT 0
);
INSERT INTO reconocimiento.configuracion(id) SELECT 1 WHERE NOT EXISTS(SELECT 1 FROM reconocimiento.configuracion WHERE id=1);
CREATE TABLE IF NOT EXISTS reconocimiento.reto (
 id VARCHAR(36) PRIMARY KEY, nonce VARCHAR(80) NOT NULL, proposito VARCHAR(30) NOT NULL,
 dni VARCHAR(8), clave TEXT NOT NULL DEFAULT '', creado TIMESTAMP WITH TIME ZONE NOT NULL,
 usado BOOLEAN NOT NULL DEFAULT FALSE, latitud DOUBLE PRECISION, longitud DOUBLE PRECISION,
 precision_m DOUBLE PRECISION, edad_ms BIGINT, ip VARCHAR(80) NOT NULL, revision BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS reconocimiento.asistencia (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, dni VARCHAR(8) NOT NULL REFERENCES reconocimiento.persona(dni),
 nombre VARCHAR(120) NOT NULL, fecha DATE NOT NULL, instante TIMESTAMP WITH TIME ZONE NOT NULL,
 metodo VARCHAR(10) NOT NULL CHECK(metodo IN ('FACIAL','HUELLA')),
 distancia DOUBLE PRECISION NOT NULL, precision_m DOUBLE PRECISION NOT NULL, ip VARCHAR(80) NOT NULL,
 similitud DOUBLE PRECISION, CONSTRAINT asistencia_unica_dia UNIQUE(dni, fecha)
);
CREATE INDEX IF NOT EXISTS asistencia_fecha_instante ON reconocimiento.asistencia(fecha,instante DESC);
ALTER TABLE reconocimiento.asistencia ADD COLUMN IF NOT EXISTS foto TEXT NOT NULL DEFAULT '';
ALTER TABLE reconocimiento.asistencia ADD COLUMN IF NOT EXISTS foto_registro TEXT NOT NULL DEFAULT '';
ALTER TABLE reconocimiento.asistencia ADD COLUMN IF NOT EXISTS umbral DOUBLE PRECISION;
ALTER TABLE reconocimiento.persona ADD COLUMN IF NOT EXISTS foto_rostro TEXT NOT NULL DEFAULT '';
ALTER TABLE reconocimiento.asistencia ADD COLUMN IF NOT EXISTS tipo_foto_registro VARCHAR(10) NOT NULL DEFAULT 'FICHA';
CREATE TABLE IF NOT EXISTS reconocimiento.ensayo_facial (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 dni_esperado VARCHAR(8),dni_reconocido VARCHAR(8),similitud DOUBLE PRECISION NOT NULL,
 similitud_esperada DOUBLE PRECISION,umbral DOUBLE PRECISION NOT NULL,margen DOUBLE PRECISION NOT NULL,
 resultado VARCHAR(30) NOT NULL,instante TIMESTAMP WITH TIME ZONE NOT NULL,
 registro_version VARCHAR(64) NOT NULL,modelo VARCHAR(80) NOT NULL
);
ALTER TABLE reconocimiento.ensayo_facial ADD COLUMN IF NOT EXISTS captura_version VARCHAR(40) NOT NULL DEFAULT 'legacy-v1';
